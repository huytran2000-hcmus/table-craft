import type {
  CheckDesign,
  ColumnDesign,
  DdlContext,
  DdlScript,
  ForeignKeyDesign,
  IndexDesign,
  ObjectChange,
  ObjectEditor,
  ObjectKind,
  TableDesign,
} from "@table-craft/plugin-api";
import {
  ddlScript,
  designError,
  NOTHING_TO_CHANGE,
  referencesClause,
  tableDesignOf,
  tableDifference,
  unchanged,
  validateDesign,
} from "@table-craft/plugin-api/sql";

const INDENT = "  ";
const IDENTITY = "GENERATED BY DEFAULT AS IDENTITY";
/** A serial column's default; the design shows it as auto-increment instead. */
const SERIAL_DEFAULT = /^nextval\(/i;

const TYPES = [
  "integer",
  "bigint",
  "smallint",
  "numeric(12, 2)",
  "text",
  "varchar(255)",
  "boolean",
  "date",
  "timestamp",
  "timestamptz",
  "uuid",
  "jsonb",
  "bytea",
  "double precision",
];

const KEYWORDS: Readonly<Record<ObjectKind, string>> = {
  table: "TABLE",
  view: "VIEW",
  materializedView: "MATERIALIZED VIEW",
  sequence: "SEQUENCE",
  function: "FUNCTION",
  procedure: "PROCEDURE",
};

export interface PostgresObjectOptions {
  /** Spells a column, index or constraint name, quoting only where needed. */
  readonly name: (identifier: string) => string;
  readonly text: (value: string) => string;
}

/** Object DDL for PostgreSQL, whose DDL is transactional, so every change runs in one transaction. */
export function postgresObjects(options: PostgresObjectOptions): ObjectEditor {
  const { name, text } = options;

  function columnDefinition(column: ColumnDesign): string {
    return [
      name(column.name),
      column.type.trim(),
      column.autoIncrement ? IDENTITY : "",
      column.nullable ? "" : "NOT NULL",
      column.default === null || column.default.trim() === "" ? "" : `DEFAULT ${column.default.trim()}`,
    ]
      .filter((part) => part !== "")
      .join(" ");
  }

  function columns(list: readonly string[]): string {
    return list.map(name).join(", ");
  }

  function foreignKey(key: ForeignKeyDesign, context: DdlContext): string {
    return `CONSTRAINT ${name(key.name)} ${referencesClause(key, context.qualifiedName(key.target.path, key.target.relation), name)}`;
  }

  function check(entry: CheckDesign): string {
    return `CONSTRAINT ${name(entry.name)} CHECK (${entry.expression.trim()})`;
  }

  function createIndex(index: IndexDesign, table: string): string {
    return `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${name(index.name)} ON ${table} (${columns(index.columns)});`;
  }

  function comment(target: string, value: string | null): string {
    return `COMMENT ON ${target} IS ${value === null || value === "" ? "NULL" : text(value)};`;
  }

  function createTable(path: readonly string[], design: TableDesign, context: DdlContext): DdlScript {
    validateDesign(design);
    const table = context.qualifiedName(path, design.name);
    const parts = [
      ...design.columns.map(columnDefinition),
      ...(design.primaryKey.length > 0 ? [`PRIMARY KEY (${columns(design.primaryKey)})`] : []),
      ...design.foreignKeys.map((key) => foreignKey(key, context)),
      ...design.checks.map(check),
    ];
    return ddlScript(
      [
        `CREATE TABLE ${table} (\n${parts.map((part) => INDENT + part).join(",\n")}\n);`,
        ...design.indexes.map((index) => createIndex(index, table)),
        ...(design.comment === null || design.comment === "" ? [] : [comment(`TABLE ${table}`, design.comment)]),
        ...design.columns
          .filter((column) => column.comment !== null && column.comment !== "")
          .map((column) => comment(`COLUMN ${table}.${name(column.name)}`, column.comment)),
      ],
      { transactional: true },
    );
  }

  function alterColumn(table: string, before: ColumnDesign, after: ColumnDesign): string[] {
    const alter = (clause: string): string => `ALTER TABLE ${table} ALTER COLUMN ${name(after.name)} ${clause};`;
    const statements: string[] = [];
    if (before.name !== after.name) {
      statements.push(`ALTER TABLE ${table} RENAME COLUMN ${name(before.name)} TO ${name(after.name)};`);
    }
    const type = after.type.trim();
    if (before.type.trim() !== type) statements.push(alter(`TYPE ${type} USING ${name(after.name)}::${type}`));
    if (before.nullable !== after.nullable) statements.push(alter(after.nullable ? "DROP NOT NULL" : "SET NOT NULL"));
    if (before.autoIncrement !== after.autoIncrement) {
      statements.push(alter(after.autoIncrement ? `ADD ${IDENTITY}` : "DROP IDENTITY IF EXISTS"));
    }
    const fallback = (after.default ?? "").trim();
    if ((before.default ?? "").trim() !== fallback) {
      statements.push(alter(fallback === "" ? "DROP DEFAULT" : `SET DEFAULT ${fallback}`));
    }
    if ((before.comment ?? "") !== (after.comment ?? "")) {
      statements.push(comment(`COLUMN ${table}.${name(after.name)}`, after.comment));
    }
    return statements;
  }

  function alterTable(path: readonly string[], design: TableDesign, context: DdlContext): DdlScript {
    validateDesign(design);
    const current = context.current;
    if (current === null) throw designError("The table is not described; synchronize the data source and try again.");
    const difference = tableDifference(current, design);
    if (unchanged(difference)) return ddlScript([], { transactional: true, notes: [NOTHING_TO_CHANGE] });
    const table = context.qualifiedName(path, current.name);
    const alter = (clause: string): string => `ALTER TABLE ${table} ${clause};`;
    const statements = [
      ...difference.droppedForeignKeys.map((key) => alter(`DROP CONSTRAINT ${name(key.name)}`)),
      ...difference.droppedChecks.map((entry) => alter(`DROP CONSTRAINT ${name(entry.name)}`)),
      ...difference.droppedIndexes.map((index) => `DROP INDEX ${context.qualifiedName(path, index.name)};`),
      ...(difference.primaryKeyChanged && current.primaryKeyName !== null
        ? [alter(`DROP CONSTRAINT ${name(current.primaryKeyName)}`)]
        : []),
      ...difference.droppedColumns.map((column) => alter(`DROP COLUMN ${name(column.name)}`)),
      ...difference.changedColumns.flatMap(({ before, after }) => alterColumn(table, before, after)),
      ...difference.addedColumns.flatMap((column) => [
        alter(`ADD COLUMN ${columnDefinition(column)}`),
        ...(column.comment === null || column.comment === ""
          ? []
          : [comment(`COLUMN ${table}.${name(column.name)}`, column.comment)]),
      ]),
      ...(difference.primaryKeyChanged && design.primaryKey.length > 0
        ? [alter(`ADD PRIMARY KEY (${columns(design.primaryKey)})`)]
        : []),
      ...difference.addedChecks.map((entry) => alter(`ADD ${check(entry)}`)),
      ...difference.addedForeignKeys.map((key) => alter(`ADD ${foreignKey(key, context)}`)),
      ...difference.addedIndexes.map((index) => createIndex(index, table)),
      ...(difference.commentChanged ? [comment(`TABLE ${table}`, design.comment)] : []),
      ...(difference.renamedTo === null ? [] : [alter(`RENAME TO ${name(difference.renamedTo)}`)]),
    ];
    return ddlScript(statements, { transactional: true });
  }

  function script(change: ObjectChange, context: DdlContext): DdlScript {
    switch (change.kind) {
      case "createTable":
        return createTable(change.path, change.design, context);
      case "alterTable":
        return alterTable(change.path, change.design, context);
      case "rename": {
        if (change.name.trim() === "") throw designError("Type the new name.");
        const target = context.qualifiedName(change.path, change.object.name);
        return ddlScript([`ALTER ${KEYWORDS[change.object.kind]} ${target} RENAME TO ${name(change.name)};`], {
          transactional: true,
        });
      }
      case "drop": {
        const target = context.qualifiedName(change.path, change.object.name);
        return ddlScript([`DROP ${KEYWORDS[change.object.kind]} ${target}${change.cascade ? " CASCADE" : ""};`], {
          transactional: true,
        });
      }
      case "truncate":
        return ddlScript(
          [`TRUNCATE TABLE ${context.qualifiedName(change.path, change.relation)}${change.cascade ? " CASCADE" : ""};`],
          { transactional: true },
        );
      case "createNamespace":
        if (change.name.trim() === "") throw designError("Name the schema.");
        return ddlScript([`CREATE SCHEMA ${name(change.name)};`], { transactional: true });
    }
  }

  return {
    features: {
      types: TYPES,
      checks: true,
      comments: true,
      cascade: true,
      truncate: true,
      namespaceKind: "schema",
      renamable: ["table", "view", "materializedView", "sequence", "function", "procedure"],
      droppable: ["table", "view", "materializedView", "sequence", "function", "procedure"],
    },
    design: (relation) =>
      tableDesignOf(relation, (column) =>
        column.autoIncrement && column.default !== null && SERIAL_DEFAULT.test(column.default) ? null : column.default,
      ),
    script,
  };
}
